-- Flatten the application for the desktop updater, which accepts plain names.
-- Each loader discards itself after use; Lua source is not kept as strings.
local jsonPath, version, output = assert(arg[1]), assert(arg[2]), assert(arg[3])
assert(version:match("^[%w%.%+_%-]+$"), "invalid build version")
local file = assert(io.open(output, "wb"))
file:write("-- Generated by EmberBSD-Spark/package.lua; edit the source modules.\n")
local function read(path)
    local input = assert(io.open(path, "rb"))
    local body = assert(input:read("*a"))
    assert(input:close())
    assert(load(body, "@" .. path, "t"))
    return body
end
local function module(name, body)
    file:write("package.preload[", string.format("%q", name), "] = function(...)\n",
        "package.preload[", string.format("%q", name), "] = nil\n", body, "\nend\n")
end
module("dkjson", read(jsonPath))
module("version", "return " .. string.format("%q", version))
for index = 4, #arg do
    local path = arg[index]
    local name = assert(path:match("([^/]+)%.lua$"))
    if name ~= "version" then module(name, read(path)) end
end
file:write("return function() return require('serve') end\n")
assert(file:close())
